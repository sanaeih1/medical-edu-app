    <p>روان‌شناسان شناختی، آسیب‌پذیری ذهن انسان به سوگیری‌های شناختی، پیش‌فرض‌های اشتباه و طیفی از خطاهای استدلالی دیگر را توصیف کرده‌اند. ذهن ما به دو روش اصلی اطلاعات را مدیریت و پردازش می‌کند، که عمدتاً به نام‌های سیستم ۱ و سیستم ۲ شناخته می‌شوند. سیستم ۱ شهودی، سریع و خودکار است یعنی همان شناخت سریع که عموماً توسط متخصصان استفاده می‌شود، اما در بسیاری از موقعیت‌ها مستعد خطا است. سیستم ۲ تحلیلی، کندتر و نیازمند تلاش می‌باشد (کانمن، ۲۰۱۲) (شکل ۲۷-۲). روان‌شناسان تخمین می‌زنند که ما در ۹۵٪ از اوقات از سیستم ۱ استفاده می‌کنیم. پزشکان بالینی معمولاً از محدودیت‌های عملکرد انسان که بر استدلال بالینی و تصمیم‌گیری‌ها اثر می‌گذارند آگاه نیستند. تفکر و تصمیم‌گیری می‌تواند تحت تأثیر زمینه یا عوامل دیگری قرار گیرد؛ مانند:</p>
