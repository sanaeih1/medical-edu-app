      <li><b>لیست مشکلات (Problem list):</b> توانایی استخراج داده‌های بالینی کلیدی از شرح حال، معاینه فیزیکی و (گاهی اوقات) نتایج آزمایشگاهی اولیه، یک مرحله کلیدی در استدلال بالینی می‌باشد. برخی مشکلات نیازمند تشخیص افتراقی هستند، اما نه همواره؛ و اکثر بیماران بیش از یک مشکل دارند.</li>
