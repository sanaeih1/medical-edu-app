    <p>در کنار پویایی گروه، شیوه مدیریت مباحثه نیز حائز اهمیت است. یکی از روش‌های تصمیم‌گیری در مورد نوع مناسب جلسه با گروه کوچک، در نظر گرفتن بسته (همگرا) یا باز (واگرا) بودن جلسه است. درک تفاوت‌های اساسی میان این دو، حائز اهمیت است؛ زیرا مباحثات و نوع پویایی آن‌ها عملکرد بسیار متفاوتی دارند. در نتیجه، انتخاب نادرست می‌تواند دردسرساز باشد. توجه داشته باشید که در جلسات طولانی‌تر (برای مثال، کارگاه‌های نیم‌روزه یا یک‌روزه)، بر اساس هدف و تکلیف جلسه، ممکن است ترکیبی از این رویکردها مورد استفاده قرار بگیرد.</p>

