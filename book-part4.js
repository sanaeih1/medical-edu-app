    <p>نحوه طبقه‌بندی سوالات مورد بحث قرار گرفته و داوران می‌توانند برآوردهای خود را تغییر دهند. نمره قبولی با استفاده از تعداد سوالات هر گروه و میانگین نسبت پاسخ‌های درست، همانطور که در جدول ۴۴-۲ نشان داده شده است محاسبه می‌شود.</p>

